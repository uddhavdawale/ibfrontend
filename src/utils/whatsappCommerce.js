export const normalizeWhatsAppPhone = (value) => {
  let digits = String(value || '').replace(/\D/g, '').replace(/^00/, '');
  if (digits.length === 11 && digits.startsWith('0')) digits = digits.slice(1);
  if (digits.length === 10) digits = `91${digits}`;
  return /^\d{8,15}$/.test(digits) ? digits : '';
};

export const buildPaymentReminderMessage = ({
  customerName,
  shopName,
  dueBalance,
  invoiceNo,
}) => {
  const formattedDue = Number(dueBalance || 0).toLocaleString('en-IN', {
    style: 'currency',
    currency: 'INR',
    minimumFractionDigits: 2,
  });
  const invoiceText = invoiceNo ? ` for invoice ${String(invoiceNo).trim()}` : '';

  return `Hello ${String(customerName || 'there').trim()},\n\nA friendly payment reminder from ${String(shopName || 'our store').trim()}. Our records show an outstanding balance${invoiceText} of ${formattedDue}.\n\nIf you have already paid, please ignore this reminder. Thank you.`;
};

export const buildDailySalesSummaryMessage = ({
  shopName,
  salesToday,
  pendingPayments,
  ordersToday,
  lowStockCount,
}) => `Daily sales summary - ${String(shopName || 'Store').trim()}

Sales today: ${Number(salesToday || 0).toLocaleString('en-IN', { style: 'currency', currency: 'INR', minimumFractionDigits: 2 })}
Orders today: ${Number(ordersToday || 0).toLocaleString('en-IN')}
Pending payments: ${Number(pendingPayments || 0).toLocaleString('en-IN', { style: 'currency', currency: 'INR', minimumFractionDigits: 2 })}
Low-stock products: ${Number(lowStockCount || 0).toLocaleString('en-IN')}

Generated by ${String(shopName || 'your store').trim()}.`;
